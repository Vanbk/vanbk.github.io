function newsDate(value) {
  if (value.length === 4) return value;
  const date = new Date(value.length === 7 ? `${value}-01T00:00:00Z` : `${value}T00:00:00Z`);
  return new Intl.DateTimeFormat('en-GB', { ...(value.length === 10 ? { day: 'numeric' } : {}), month: 'short', year: 'numeric', timeZone: 'UTC' }).format(date);
}
const authors = (p) => p.authors.map((name) => /^(Anh-Van Vu|Van Anh Vu)$/.test(name) ? `<strong>${e(name)}</strong>` : e(name)).join(', ');
export function bibtex(p) {
  const fields = {
    title: `{${p.title}}`,
    author: p.authors.map((name) => {
      const parts = name.split(' ');
      return `${parts.pop()}, ${parts.join(' ')}`;
    }).join(' and '),
    year: p.year,
    ...(p.type === 'preprint' ? { eprint: p.venue.replace('arXiv:', ''), archivePrefix: 'arXiv', primaryClass: 'cs.RO' } : { booktitle: p.venue }),
    ...(p.pages ? { pages: p.pages.replace('–', '--') } : {}),
    doi: p.doi,
    url: p.url
  };
  return `@${p.type === 'preprint' ? 'misc' : 'inproceedings'}{${p.id},\n${Object.entries(fields).map(([key, value]) => `  ${key} = {${value}}`).join(',\n')}\n}`;
}

